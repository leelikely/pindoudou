// 根据当前品牌生成用于 PindouConverter 的色盘数组
export function buildPalette(brand = "MARD") {
    const palette = [];
    const seen = new Set();
    for (const [hex, mapObj] of Object.entries(COLOR_SYSTEM_MAPPING)) {
        const code = mapObj[brand];
        if (!code || code === "-") continue;
        const key = brand + ":" + code;
        if (seen.has(key)) continue;
        seen.add(key);
        palette.push({
            id: key,
            symbol: code,
            hex: hex.toUpperCase(),
            brand: brand,
            name: brand + " " + code,
        });
    }
    return palette;
}



