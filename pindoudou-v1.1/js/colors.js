// 辅助：生成 "X1" ~ "Xnn" 的色号数组（补零对齐，如 A01）
function rangeCodes(prefix, from, to, pad = true) {
    const codes = [];
    for (let i = from; i <= to; i++) {
        codes.push(pad ? prefix + String(i).padStart(2, '0') : prefix + i);
    }
    return codes;
}

